def main():
    S, R, N = load("setup.yaml"), load("rsa.yaml"), load("neg.yaml")
    V = load("volume.yaml")
    errs = validate(S, R, N)
    if errs:
        print("검증 실패:", file=sys.stderr)
        for e in errs:
            print(f"  - {e}", file=sys.stderr)
        return 1
    out = build(S, R, N, V)
    dest = os.path.join(ROOT, "docs", "campaign_setup_spec.md")
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    n_ag = sum(len(c["groups"]) for c in S["campaigns"])
    n_kw = sum(len(g["exact"]) + len(g["phrase"])
               for c in S["campaigns"] for g in c["groups"])
    print(f"검증 통과 · 생성: {dest} ({len(out)}줄)")
    print(f"캠페인 {len(S['campaigns'])} / 광고그룹 {n_ag} / 키워드 {n_kw} / "
          f"RSA {len(R)} / 헤드라인 {sum(len(v['headlines']) for v in R.values())}")
    return 0


