def load(name):
    with open(os.path.join(SPEC, name), encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def validate(S, R, N):
    errs = []
    need = {g["rsa"] for c in S["campaigns"] for g in c["groups"]}
    for miss in sorted(need - set(R)):
        errs.append(f"RSA '{miss}' 문안이 rsa.yaml 에 없습니다.")

    for key, v in R.items():
        heads, descs = v["headlines"], v["descriptions"]
        if len(heads) > 15:
            errs.append(f"[{key}] 헤드라인 {len(heads)}개 — 최대 15개")
        if len(set(heads)) != len(heads):
            errs.append(f"[{key}] 중복 헤드라인")
        if not 2 <= len(descs) <= 4:
            errs.append(f"[{key}] 설명 {len(descs)}개 — 2~4개")
        for h in heads:
            if width(h) > 30:
                errs.append(f"[{key}] 헤드라인 '{h}' {width(h)}자 — 최대 30")
        for d in descs:
            if width(d) > 90:
                errs.append(f"[{key}] 설명 '{d}' {width(d)}자 — 최대 90")
        for t in heads + descs:
            for b in BANNED:
                if b in t:
                    errs.append(f"[{key}] 금지 표현 '{b}' 포함: {t}")

    # 제외 키워드가 타겟 키워드를 막지 않는지
    for c in S["campaigns"]:
        key = {"헬로벨": "bell", "헬로클릭": "click"}.get(c["product"])
        for g in c["groups"]:
            for kw in g["exact"] + g["phrase"]:
                for t in N["account"]:
                    if str(t) in kw:
                        errs.append(f"[{g['name']}] '{kw}' 가 계정 제외어 "
                                    f"'{t}' 에 막힙니다")
                if not key:
                    continue
                for t in N[key].get("phrase", []):
                    if str(t) in kw:
                        errs.append(f"[{g['name']}] '{kw}' 가 {key} 구문 제외어 "
                                    f"'{t}' 에 막힙니다")
                for t in N[key].get("exact", []):
                    if str(t) == kw:
                        errs.append(f"[{g['name']}] '{kw}' 가 {key} 정확 제외어 "
                                    f"'{t}' 와 동일합니다")

    share = sum(c["share"] for c in S["campaigns"]) + S.get("reserve_share", 0)
    if abs(share - 1.0) > 0.001:
        errs.append(f"예산 비중 합계가 {share:.3f} 입니다 (1.0 이어야 함)")
    return errs


